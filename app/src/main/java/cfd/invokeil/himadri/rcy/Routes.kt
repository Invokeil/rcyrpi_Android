package cfd.invokeil.himadri.rcy

/** Type-safe navigation routes. */
object Routes {
    const val MAIN = "main"
    const val SPLASH = "splash"
    const val ONBOARDING = "onboarding"
    const val HOME = "home"
    const val NOTICES = "notices"
    const val NOTICE_DETAIL = "notice/{id}"
    const val EVENTS = "events"
    const val EVENT_DETAIL = "event/{id}"
    const val FUND_DETAIL = "fund/{id}"
    const val LEADERBOARD = "leaderboard"
    const val PAYMENTS = "payments"
    const val PAYMENT_CHECKOUT = "pay/checkout/{itemId}"
    const val PAYMENT_SUCCESS = "pay/success?tran={tran}&item={item}&amount={amount}"
    const val EMERGENCY_REQUEST = "emergency-request"
    const val EMERGENCY_FEED = "emergency-feed"
    const val LOGIN = "login"
    const val SIGNUP = "signup"
    const val FORGOT = "forgot"
    const val RESET = "reset?token={token}"
    const val RESET_TOKENLESS = "reset_tokenless"
    const val PROFILE = "profile"
    const val PROFILE_EDIT = "profile-edit"
    const val ID_CARD = "id-card"
    const val CERTIFICATES = "certificates"
    const val CERTIFICATE_DETAIL = "certificate/{id}"
    const val CHANGE_PASSWORD = "change-password"
    const val NOTIFICATIONS = "notifications"
    const val VERIFY = "verify?code={code}"
    const val TERMS = "terms"
    const val SETTINGS = "settings"

    fun notice(id: String) = "notice/$id"
    fun event(id: String) = "event/$id"
    fun fund(id: String) = "fund/$id"
    fun checkout(itemId: String) = "pay/checkout/$itemId"
    fun paySuccess(tran: String, item: String, amount: String) = "pay/success?tran=$tran&item=$item&amount=$amount"
    fun reset(token: String) = "reset?token=$token"
    fun verify(code: String? = null) = if (code.isNullOrBlank()) "verify" else "verify?code=$code"
}
